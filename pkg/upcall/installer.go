package upcall

import (
	"context"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	utilversion "k8s.io/apimachinery/pkg/util/version"
	"k8s.io/klog/v2"
)

const (
	containerProxyPath      = "/usr/bin/lustre-host-proxy"
	hostUdevDir             = "/host_etc_udev"
	hostProxyPath           = hostUdevDir + "/lustre-host-proxy"
	hostRulesPath           = hostUdevDir + "/rules.d/99-lustre.rules"
	hostUpcallSymlinkPath   = hostUdevDir + "/" + iamUpcallBinary
	hostTargetProxyPath     = "/etc/udev/lustre-host-proxy"
	hostUpcallSymlinkTarget = "/etc/udev/l_gssiam_upcall"

	lctlTimeout = 15 * time.Second

	udevRuleContent = `# Generated by Lustre CSI Driver Node Init. Do not edit.
SUBSYSTEM=="lustre", ACTION=="change", ENV{PARAM}=="?*", RUN+="/etc/udev/lustre-host-proxy /usr/sbin/lctl set_param $env{PARAM}=$env{SETTING}"
`
)

var minGSSIAMVersion = utilversion.MustParseGeneric("2.16.0")

// SetupHostArtifacts deploys the static Go proxy binary and the udev rules to the host filesystem via the /host_etc_udev mount.
func SetupHostArtifacts() error {
	klog.Infof("Initializing Lustre upcall host artifacts via %s", hostUdevDir)

	// 1. Verify host mount exists.
	if _, err := os.Stat(hostUdevDir); err != nil {
		return fmt.Errorf("host udev mount directory %s missing or inaccessible: %w", hostUdevDir, err)
	}

	// 2. Copy the proxy binary from container to host.
	if err := copyFile(containerProxyPath, hostProxyPath); err != nil {
		return fmt.Errorf("failed to copy proxy binary to host: %w", err)
	}

	// 3. Make the host proxy executable.
	if err := os.Chmod(hostProxyPath, 0755); err != nil {
		return fmt.Errorf("failed to set executable permissions on host proxy: %w", err)
	}
	klog.Infof("Successfully installed host proxy binary at %s", hostProxyPath)

	// 4. Ensure rules.d directory exists on host.
	rulesDir := filepath.Dir(hostRulesPath)
	if err := os.MkdirAll(rulesDir, 0755); err != nil {
		return fmt.Errorf("failed to create host rules directory %s: %w", rulesDir, err)
	}

	// 5. Write the udev rules file
	if err := os.WriteFile(hostRulesPath, []byte(udevRuleContent), 0644); err != nil {
		return fmt.Errorf("failed to write udev rules to host at %s: %w", hostRulesPath, err)
	}
	klog.Infof("Successfully installed udev rules at %s", hostRulesPath)

	// 6. Verify IAM upcall binary exists in container (only present in lustre-client-utils >= 2.16).
	if _, err := os.Stat(iamUpcallPath); err != nil {
		if os.IsNotExist(err) {
			klog.Infof("Skipping IAM upcall symlink and kernel tunable setup: %s not found in container (lustre-client-utils < 2.16)", iamUpcallPath)
		} else {
			klog.Errorf("Failed to stat %s; skipping IAM upcall setup: %v", iamUpcallPath, err)
		}
		return nil
	}

	// 7. Create symbolic link on host pointing to the proxy: /etc/udev/l_gssiam_upcall -> /etc/udev/lustre-host-proxy
	if err := os.Remove(hostUpcallSymlinkPath); err != nil && !os.IsNotExist(err) {
		klog.Errorf("Failed to remove existing symlink at %s; skipping IAM upcall setup: %v", hostUpcallSymlinkPath, err)
		return nil
	}
	if err := os.Symlink(hostTargetProxyPath, hostUpcallSymlinkPath); err != nil {
		klog.Errorf("Failed to create upcall symlink at %s; skipping IAM upcall setup: %v", hostUpcallSymlinkPath, err)
		return nil
	}
	klog.Infof("Successfully created host upcall symlink at %s -> %s", hostUpcallSymlinkPath, hostTargetProxyPath)

	// 8. Configure kernel tunable sptlrpc.gssiam.gssiam_upcall directly to the symlink (Lustre >= 2.16).
	if err := configureGSSIAMUpcallTunable(); err != nil {
		klog.Errorf("Failed to configure sptlrpc.gssiam.gssiam_upcall tunable: %v", err)
	}

	return nil
}

// lustreSupportsGSSIAM parses `lctl get_param -n version` output and reports
// whether the running Lustre client is >= 2.16.
func lustreSupportsGSSIAM(verOut string) (bool, string, error) {
	verStr := strings.TrimPrefix(strings.TrimSpace(verOut), "version=")
	v, err := utilversion.ParseGeneric(verStr)
	if err != nil {
		return false, verStr, err
	}
	return !v.LessThan(minGSSIAMVersion), verStr, nil
}

// configureGSSIAMUpcallTunable checks the active Lustre version and, if >= 2.16,
// sets the Lustre kernel tunable sptlrpc.gssiam.gssiam_upcall to point to the
// host proxy symlink at /etc/udev/l_gssiam_upcall.
func configureGSSIAMUpcallTunable() error {
	ctx, cancel := context.WithTimeout(context.Background(), lctlTimeout)
	defer cancel()

	verOut, err := exec.CommandContext(ctx, lctlPath, "get_param", "-n", "version").Output()
	if err != nil {
		return fmt.Errorf("querying lustre version: %w (output: %s)", err, strings.TrimSpace(string(verOut)))
	}

	ok, verStr, err := lustreSupportsGSSIAM(string(verOut))
	if err != nil {
		return fmt.Errorf("parsing lustre version %q: %w", verStr, err)
	}
	if !ok {
		klog.Infof("Skipping sptlrpc.gssiam.gssiam_upcall setup: Lustre %s < %s", verStr, minGSSIAMVersion)
		return nil
	}

	paramArg := "sptlrpc.gssiam.gssiam_upcall=" + hostUpcallSymlinkTarget
	if out, err := exec.CommandContext(ctx, lctlPath, "set_param", paramArg).CombinedOutput(); err != nil {
		return fmt.Errorf("setting %s: %w (output: %s)", paramArg, err, strings.TrimSpace(string(out)))
	}
	klog.Infof("Configured %s (Lustre %s)", paramArg, verStr)
	return nil
}

func copyFile(src, dst string) error {
	sourceFile, err := os.Open(src)
	if err != nil {
		return err
	}
	defer func() { _ = sourceFile.Close() }()

	destFile, err := os.OpenFile(dst, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0755)
	if err != nil {
		return err
	}
	defer func() { _ = destFile.Close() }()

	if _, err = io.Copy(destFile, sourceFile); err != nil {
		return err
	}
	return destFile.Sync()
}
